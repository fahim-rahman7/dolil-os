import type { Office } from '@prisma/client';
import { bnDigits, type Block, type Cell } from './bnDeed.js';

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const t = (s: string) => esc(bnDigits(s)).replace(/\n/g, '<br>');

function cell(c: Cell, tag: 'td' | 'th'): string {
  const o = typeof c === 'string' ? { text: c } : c;
  const attrs = [o.colspan ? `colspan="${o.colspan}"` : '', o.align ? `style="text-align:${o.align}"` : ''].filter(Boolean).join(' ');
  return `<${tag} ${attrs}>${o.bold ? '<b>' : ''}${t(o.text)}${o.bold ? '</b>' : ''}</${tag}>`;
}

function renderBlock(b: Block): string {
  switch (b.t) {
    case 'title':
      return `<h1>${t(b.text)}</h1>${b.sub ? `<div class="sub">${t(b.sub)}</div>` : ''}`;
    case 'heading':
      return `<h2>${t(b.text)}</h2>`;
    case 'para':
      return `<p>${b.bold ? '<b>' : ''}${t(b.text)}${b.bold ? '</b>' : ''}</p>`;
    case 'gap':
      return '<div class="gap"></div>';
    case 'table': {
      const cols = b.widths.map((w) => `<col style="width:${w}%">`).join('');
      const rows = b.rows
        .map((r, i) => `<tr>${r.map((c) => cell(c, b.head && i === 0 ? 'th' : 'td')).join('')}</tr>`)
        .join('');
      return `<table>${cols}${rows}</table>`;
    }
    case 'card': {
      const kv = b.rows.map(([k, v]) => `<tr><td class="k">${t(k)}</td><td class="c">:</td><td>${t(v)}</td></tr>`).join('');
      return `<div class="card"><table class="kv">${kv}</table><div class="photo">${t(b.photo)}</div></div>`;
    }
    case 'sign':
      return `<div class="sign"><div>${t(b.left)}</div><div>${t(b.right)}</div></div>`;
  }
}

