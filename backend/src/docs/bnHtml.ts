/** Full HTML document: used for the on-screen preview, browser print and server PDF. */
export function renderBnHtml(blocks: Block[], office: Office, opts: { watermark: string | null; title: string; font?: string }): string {
  const font = opts.font || office.printFont;
  const head = [office.name, [office.address, office.phone].filter(Boolean).join(' · ')].filter(Boolean).join('\n');
  return `<!doctype html><html lang="bn"><head><meta charset="utf-8"><title>${esc(opts.title)}</title>
<style>@page { size: ${office.printPageSize}; margin: ${office.printMarginMm}mm; }${CSS}
body { font-family: "${esc(font)}","SolaimanLipi","Kalpurush","Nirmala UI","Noto Sans Bengali",serif; }</style></head><body>
${opts.watermark ? `<div class="wm">${esc(opts.watermark)}</div>` : ''}
<div style="position:relative;z-index:1">
${office.printHeader ? `<div style="text-align:center;font-size:10pt;white-space:pre-line;margin-bottom:6px">${t(office.printHeader)}</div>` : ''}
${blocks.map(renderBlock).join('\n')}
<div class="foot">${t(office.printFooter ?? '')}${office.printFooter ? '\n' : ''}${esc(head)}\nGenerated by Dolil OS as a drafting aid. Not a legally validated instrument; verify all facts, applicable law and approved wording before execution or registration.</div>
</div></body></html>`;
}
